using Microsoft.EntityFrameworkCore;

namespace AtlasCRM.Infrastructure.Persistence;

public static class DatabaseInitializer
{
    public static async Task InitializeAsync(AtlasCrmDbContext dbContext)
    {
        await dbContext.Database.EnsureCreatedAsync();
        await EnsureRuntimeSchemaAsync(dbContext);
    }

    public static async Task EnsureRuntimeSchemaAsync(AtlasCrmDbContext dbContext)
    {
        await dbContext.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS documents (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                company_id BIGINT NOT NULL REFERENCES companies(id),
                title VARCHAR(180) NOT NULL,
                description TEXT NULL,
                type INTEGER NOT NULL,
                url TEXT NULL,
                stored_file_name VARCHAR(260) NULL,
                original_file_name VARCHAR(260) NULL,
                content_type VARCHAR(120) NULL,
                size_bytes BIGINT NULL,
                created_at_utc TIMESTAMPTZ NOT NULL,
                updated_at_utc TIMESTAMPTZ NULL
            );
            CREATE INDEX IF NOT EXISTS ix_documents_company_id ON documents (company_id);
            CREATE INDEX IF NOT EXISTS ix_documents_company_type ON documents (company_id, type);
            ALTER TABLE documents ADD COLUMN IF NOT EXISTS sector VARCHAR(60) NULL;
            ALTER TABLE documents ADD COLUMN IF NOT EXISTS tags_json TEXT NULL;
            ALTER TABLE documents ADD COLUMN IF NOT EXISTS is_onboarding BOOLEAN NOT NULL DEFAULT FALSE;
            ALTER TABLE documents ADD COLUMN IF NOT EXISTS visibility VARCHAR(20) NOT NULL DEFAULT 'private';

            ALTER TABLE leads ADD COLUMN IF NOT EXISTS qualification_temperature INTEGER NOT NULL DEFAULT 2;
            ALTER TABLE leads ADD COLUMN IF NOT EXISTS qualification_score INTEGER NOT NULL DEFAULT 0;
            ALTER TABLE leads ADD COLUMN IF NOT EXISTS qualification_notes VARCHAR(500) NULL;
            ALTER TABLE leads ADD COLUMN IF NOT EXISTS extra_data_json TEXT NULL;
            CREATE INDEX IF NOT EXISTS ix_leads_company_qualification_temperature ON leads (company_id, qualification_temperature);

            CREATE TABLE IF NOT EXISTS user_permissions (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                company_id BIGINT NOT NULL REFERENCES companies(id),
                user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                permission VARCHAR(80) NOT NULL,
                created_at_utc TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                updated_at_utc TIMESTAMPTZ NULL
            );
            CREATE UNIQUE INDEX IF NOT EXISTS ix_user_permissions_company_user_permission
                ON user_permissions (company_id, user_id, permission);
            
            CREATE TABLE IF NOT EXISTS finance_entries (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                company_id BIGINT NOT NULL REFERENCES companies(id),
                occurred_at_utc TIMESTAMPTZ NOT NULL,
                type VARCHAR(16) NOT NULL,
                category VARCHAR(120) NOT NULL,
                amount NUMERIC(18,2) NOT NULL,
                currency VARCHAR(10) NOT NULL,
                notes TEXT NULL,
                attachment_file_name VARCHAR(260) NULL,
                created_at_utc TIMESTAMPTZ NOT NULL,
                updated_at_utc TIMESTAMPTZ NULL
            );
            CREATE INDEX IF NOT EXISTS ix_finance_entries_company_id ON finance_entries (company_id);
            """);
    }
}
